    /**
     * Resolve enum case from currency symbol.
     *
     * @param string $symbol
     *
     * @return static|null
     */
    public static function fromSymbol($symbol)
    {
        return collect(self::cases())
            ->first(fn(self $case) => $case->symbolGrapheme() === $symbol);
    }

    /**
     * Get all currency symbols mapped by code.
     *
     * @return array<string, string>
     */
    public static function symbolMap()
    {
        return array_reduce(self::cases(), function ($carry, self $case) {
            $carry[$case->value] = $case->symbolGrapheme();
            return $carry;
        }, []);
    }

    /**
     * Get all currency symbols.
     *
     * @return string[]
     */
    public static function symbols()
    {
        return array_map(
            fn(self $case) => $case->symbolGrapheme(),
            self::cases()
        );
    }
